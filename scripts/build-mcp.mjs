// Bundles the MCP server's Vercel entry (mcp/vercel.ts + the engine and site code it imports)
// into api/mcp.js. npm packages stay external: Vercel installs them and traces the imports.
// The bundle is committed so the deployment never depends on a build step it might skip;
// test-mcp checks it is up to date. Run: npm run build:mcp

import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const OUT = fileURLToPath(new URL('../api/mcp.js', import.meta.url));

export async function bundle() {
  const r = await build({
    entryPoints: [fileURLToPath(new URL('../mcp/vercel.ts', import.meta.url))],
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    packages: 'external',
    write: false,
    legalComments: 'none',
    banner: { js: '// GENERATED by `npm run build:mcp` from mcp/ and src/. Do not edit.' },
    logLevel: 'silent',
  });
  return r.outputFiles[0].text;
}

if (process.argv[1] && path.resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase()) {
  const text = await bundle();
  const check = process.argv.includes('--check');
  let old = '';
  try {
    old = readFileSync(OUT, 'utf8');
  } catch {}
  if (check) {
    if (old !== text) {
      console.error('api/mcp.js is stale: run npm run build:mcp');
      process.exit(1);
    }
    console.log('api/mcp.js is up to date');
  } else {
    writeFileSync(OUT, text);
    console.log(`api/mcp.js written (${(text.length / 1024).toFixed(0)} KB)`);
  }
}
